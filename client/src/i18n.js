function buildBidirectionalMap(items) {
    const map = {};
    items.forEach(item => {
        if (item.id) map[item.id.toLowerCase().trim()] = item;
        if (item.en) map[item.en.toLowerCase().trim()] = item;
    });
    return map;
}

const pocketMap = buildBidirectionalMap(rawPocketTranslations);
const categoryMap = buildBidirectionalMap(rawCategoryTranslations);
const descriptionMap = buildBidirectionalMap(rawDescriptionTranslations);

let currentLang = localStorage.getItem('lang') || 'id';

export function t(key) {
    return translations[currentLang]?.[key] || translations.id[key] || key;
}

export function setLang(lang) {
    currentLang = lang;
    localStorage.setItem('lang', lang);
}

export function getLang() {
    return currentLang;
}

export function detectLang() {
    const saved = localStorage.getItem('lang');
    if (saved) return saved;
    const browserLang = navigator.language || navigator.userLanguage;
    return browserLang?.startsWith('en') ? 'en' : 'id';
}

export function translatePocketName(name) {
    if (!name) return '';
    const key = name.toLowerCase().trim();
    if (pocketMap[key]) {
        return pocketMap[key][currentLang];
    }
    if (currentLang === 'en') {
        return name
            .replace(/\bdompet\b/gi, 'Wallet')
            .replace(/\btabungan\b/gi, 'Savings')
            .replace(/\bdarurat\b/gi, 'Emergency')
            .replace(/\brekening\b/gi, 'Account')
            .replace(/\bkartu kredit\b/gi, 'Credit Card')
            .replace(/\binvestasi\b/gi, 'Investment');
    } else {
        return name
            .replace(/\bwallet\b/gi, 'Dompet')
            .replace(/\bsavings\b/gi, 'Tabungan')
            .replace(/\bemergency\b/gi, 'Darurat')
            .replace(/\baccount\b/gi, 'Rekening')
            .replace(/\bcredit card\b/gi, 'Kartu Kredit')
            .replace(/\binvestment\b/gi, 'Investasi');
    }
}

